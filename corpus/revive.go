package main

import (
	"encoding/json"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

type reviveReport struct {
	Pos  position
	Rule string
}

// runRevive runs revive, through golangci-lint, over every module of p.
func (r *runner) runRevive(lint string, p project, dir string) ([]reviveReport, error) {
	mods, err := modules(dir)
	if err != nil {
		return nil, err
	}

	config := filepath.Join(r.root, "corpus", "golangci.yaml")

	var reports []reviveReport

	seen := map[reviveReport]bool{}
	generated := map[string]bool{}

	for _, mod := range mods {
		modDir := filepath.Join(dir, mod)

		// golangci-lint exits with a non-zero status when it reports anything, so only output that can't be read fails.
		out, runErr := run(r.targetCommand(modDir, lint, "run", "--config", config, "./..."))

		var res struct {
			Issues []struct {
				Text string
				Pos  struct {
					Filename     string
					Line, Column int
				}
			}
		}

		if strings.TrimSpace(out) == "" {
			log.Printf("%s %s: skipped, as golangci-lint reported nothing it could analyse: %v", p.Name, mod, runErr)
			continue
		}

		// A summary follows the JSON.
		if err := json.NewDecoder(strings.NewReader(out)).Decode(&res); err != nil {
			return nil, fmt.Errorf("%s %s: reading golangci-lint's output: %w (%w)", p.Name, mod, err, runErr)
		}

		for _, is := range res.Issues {
			file := is.Pos.Filename
			if !filepath.IsAbs(file) {
				file = filepath.Join(modDir, file)
			}

			pos, err := relPosition(p.Name, dir, file, is.Pos.Line, is.Pos.Column)
			if err != nil {
				return nil, err
			}

			rep := reviveReport{Pos: pos, Rule: strings.SplitN(is.Text, ":", 2)[0]}
			if seen[rep] || isGenerated(generated, filepath.Join(dir, pos.File)) {
				continue
			}

			seen[rep] = true

			reports = append(reports, rep)
		}
	}

	slices.SortFunc(reports, func(a, b reviveReport) int {
		if c := a.Pos.compare(b.Pos); c != 0 {
			return c
		}

		return strings.Compare(a.Rule, b.Rule)
	})

	return reports, nil
}

func renderRevive(reports []reviveReport) string {
	var b strings.Builder

	b.WriteString("# What revive reports on the corpus. Generated by \"go run . revive\".\n")

	for _, r := range reports {
		fmt.Fprintf(&b, "%s %s\n", r.Pos, r.Rule)
	}

	return b.String()
}

func readRevive(name string) ([]reviveReport, error) {
	b, err := os.ReadFile(name)
	if err != nil {
		return nil, err
	}

	var reports []reviveReport

	for _, line := range strings.Split(string(b), "\n") {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}

		fields := strings.Fields(line)
		if len(fields) != 3 {
			return nil, fmt.Errorf("%s: unexpected line %q", name, line)
		}

		pos, err := parseRelPosn(fields[0], fields[1])
		if err != nil {
			return nil, fmt.Errorf("%s: %w", name, err)
		}

		reports = append(reports, reviveReport{Pos: pos, Rule: fields[2]})
	}

	return reports, nil
}

// parseRelPosn reads a "file:line:col" position, with file relative to the project.
func parseRelPosn(proj, posn string) (position, error) {
	parts := strings.Split(posn, ":")
	if len(parts) != 3 {
		return position{}, fmt.Errorf("unexpected position %q", posn)
	}

	line, err := strconv.Atoi(parts[1])
	if err != nil {
		return position{}, fmt.Errorf("unexpected position %q: %w", posn, err)
	}

	col, err := strconv.Atoi(parts[2])
	if err != nil {
		return position{}, fmt.Errorf("unexpected position %q: %w", posn, err)
	}

	return position{Project: proj, File: parts[0], Line: line, Col: col}, nil
}
